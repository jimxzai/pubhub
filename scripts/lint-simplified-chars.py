def scan(paths):
    findings = []
    for p in paths:
        for i, line in enumerate(open(p, encoding='utf8'), 1):
            bad = sorted({c for c in line if c in PAIRS})
            if bad:
                fix = '  '.join(f'{c}→{PAIRS[c]}' for c in bad)
                findings.append((p, i, fix, line.strip()[:80]))
    return findings

args = sys.argv[1:] or ['books/bible']
paths = []
for a in args:
    paths.extend(sorted(glob.glob(os.path.join(a, '**', '*.md'), recursive=True)) if os.path.isdir(a) else [a])
f = scan(paths)
for p, i, fix, t in f:
    print(f'{p}:{i}  [{fix}]  {t}')
print(f'\nscanned {len(paths)} file(s); simplified-character findings: {len(f)}')
sys.exit(1 if f else 0)
